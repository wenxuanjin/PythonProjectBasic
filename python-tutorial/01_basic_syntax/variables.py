# ============================================================
# 一、什么是变量？
# ============================================================
#
# 变量就像一个"盒子"，用来存储数据。
# 你可以给这个盒子起一个名字，然后把数据放进去。
# 之后通过这个名字，就可以取出或修改里面的数据。
#
# 生活中的例子：
# - 你的名字就是一个"变量"，指向你这个人
# - 手机通讯录里的联系人名字，指向对应的电话号码


# ============================================================
# 二、定义变量
# ============================================================

# 在 Python 中，定义变量非常简单：
# 变量名 = 值

# 定义一个存储姓名的变量
name = "张三"

# 定义一个存储年龄的变量
age = 25

# 定义一个存储身高的变量（单位：米）
height = 1.75

# 定义一个存储是否是学生的变量
is_student = True

# 使用 print() 输出变量的值
print("姓名:", name)      # 输出：姓名: 张三
print("年龄:", age)       # 输出：年龄: 25
print("身高:", height)    # 输出：身高: 1.75
print("是学生:", is_student)  # 输出：是学生: True


# ============================================================
# 三、变量命名规范
# ============================================================
#
# Python 变量命名有以下规则：
#
# 【必须遵守的规则】
# 1. 只能包含字母、数字、下划线
# 2. 不能以数字开头
# 3. 不能使用 Python 关键字（如 if, for, while 等）
# 4. 区分大小写（name 和 Name 是两个不同的变量）
#
# 【建议遵守的规范】
# 1. 使用有意义的名字（user_name 比 x 好）
# 2. 使用小写字母和下划线（snake_case 风格）
# 3. 避免使用单个字母（除了循环变量 i, j, k）
# 4. 避免使用拼音，尽量使用英文

# 合法的变量名示例
user_name = "李四"
user_age = 30
_private_var = "私有变量"
userName2 = "王五"  # 合法但不推荐，建议用 user_name_2

# 不合法的变量名（取消注释会报错）
# 2name = "错误"      # 不能以数字开头
# user-name = "错误"  # 不能包含减号
# for = "错误"        # 不能使用关键字

# 查看 Python 的所有关键字
import keyword
print("\nPython 关键字列表:")
print(keyword.kwlist)


# ============================================================
# 四、变量的赋值与修改
# ============================================================

# 变量可以随时修改值
score = 60
print("\n初始分数:", score)  # 输出：60

score = 80  # 修改变量的值
print("修改后分数:", score)  # 输出：80

score = score + 10  # 在原来的基础上加 10
print("加分后:", score)  # 输出：90

# 简写形式
score += 5  # 等同于 score = score + 5
print("再加分:", score)  # 输出：95


# ============================================================
# 五、多变量赋值
# ============================================================

# 同时给多个变量赋相同的值
x = y = z = 0
print("\nx =", x, ", y =", y, ", z =", z)  # 输出：x = 0 , y = 0 , z = 0

# 同时给多个变量赋不同的值
a, b, c = 1, 2, 3
print("a =", a, ", b =", b, ", c =", c)  # 输出：a = 1 , b = 2 , c = 3

# 交换两个变量的值（Python 特有的简洁写法）
m = 10
n = 20
print("\n交换前: m =", m, ", n =", n)

m, n = n, m  # 交换
print("交换后: m =", m, ", n =", n)


# ============================================================
# 六、查看变量类型
# ============================================================

# 使用 type() 函数可以查看变量的类型
name = "张三"
age = 25
height = 1.75
is_student = True

print("\nname 的类型:", type(name))        # <class 'str'>
print("age 的类型:", type(age))            # <class 'int'>
print("height 的类型:", type(height))      # <class 'float'>
print("is_student 的类型:", type(is_student))  # <class 'bool'>


# ============================================================
