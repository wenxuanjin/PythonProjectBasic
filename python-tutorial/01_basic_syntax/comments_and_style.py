# ============================================================
# 一、什么是注释？
# ============================================================
#
# 注释是代码中的说明文字，不会被 Python 执行。
# 注释的作用：
# 1. 解释代码的功能和逻辑
# 2. 帮助自己和他人理解代码
# 3. 临时禁用某些代码（调试时常用）
#
# 好的注释能让代码更易读、更易维护。


# ============================================================
# 二、单行注释
# ============================================================

# 单行注释以 # 开头
# 从 # 到行末的内容都是注释

# 这是一个单行注释
print("Hello")  # 这也是注释，在代码后面

# 计算圆的面积
radius = 5  # 半径
pi = 3.14159  # 圆周率
area = pi * radius ** 2  # 面积 = π * r²
print(f"圆的面积: {area}")


# ============================================================
# 三、多行注释
# ============================================================

# 方式一：多个单行注释
# 这是第一行注释
# 这是第二行注释
# 这是第三行注释

# 方式二：使用三引号（通常用于文档字符串）
"""
这是多行注释的第一行
这是多行注释的第二行
这是多行注释的第三行

三引号可以是双引号 ''' 或单引号 '''
"""

'''
这也是多行注释
使用单引号
'''


# ============================================================
# 四、文档字符串（Docstring）
# ============================================================

# 文档字符串是一种特殊的注释，用于描述模块、函数、类的功能
# 它位于定义的第一行，使用三引号

def calculate_area(length, width):
    """
    计算矩形的面积

    参数:
        length: 矩形的长度
        width: 矩形的宽度

    返回:
        矩形的面积
    """
    return length * width


# 可以通过 __doc__ 属性查看文档字符串
print("函数文档:")
print(calculate_area.__doc__)

# 也可以使用 help() 函数查看
# help(calculate_area)


# ============================================================
# 五、注释的最佳实践
# ============================================================

# 【好的注释】

# 1. 解释"为什么"而不是"是什么"
x=0
# 不好的注释：
x = x + 1  # x 加 1（这是废话，代码已经说明了）

# 好的注释：
x = x + 1  # 补偿数组索引从 0 开始的偏移


# 2. 解释复杂的业务逻辑
years_of_service=6
# 根据公司政策，工作满 5 年的员工可以享受额外 3 天年假
if years_of_service >= 5:
    extra_vacation = 3
else:
    extra_vacation = 0

# 3. 标记待办事项
# TODO: 这里需要添加输入验证
# FIXME: 这个算法在大数据量时性能较差
# NOTE: 这个函数依赖于外部 API

# 4. 解释不明显的代码
number=10
# 使用位运算判断奇偶（比 % 2 更快）
is_even = (number & 1) == 0


# 【不好的注释】

# 1. 注释与代码不一致（最危险的注释）
# 计算两数之和（实际是计算乘积，注释过时了）
# result = a * b

# 2. 注释掉的代码不删除
# old_function()
# another_old_function()
# 如果代码不需要了，应该删除而不是注释掉

# 3. 过于明显的注释
# i = 0  # 将 i 设为 0
# 这种注释没有任何价值


# ============================================================
# 六、Python 代码风格（PEP 8）
# ============================================================

# PEP 8 是 Python 官方的代码风格指南
# 遵循 PEP 8 可以让代码更规范、更易读

# 【缩进】
# 使用 4 个空格进行缩进，不要使用 Tab
def good_function():
    if True:
        print("正确的缩进")


# 【行长度】
# 每行代码不超过 79 个字符
# 如果太长，可以换行

# 太长的行：
# result = some_function(argument1, argument2, argument3, argument4, argument5)

# 换行后：
# result = some_function(
#     argument1,
#     argument2,
#     argument3,
#     argument4,
#     argument5
# )


# 【空行】
# 顶层函数和类之间空两行
# 类中的方法之间空一行


def function_one():
    pass


def function_two():
    pass


# 【空格】
# 运算符两边加空格
x = 1 + 2  # 好
y = 1+2    # 不好

# 逗号后面加空格
numbers = [1, 2, 3]  # 好
numbers = [1,2,3]    # 不好

# 函数参数的等号两边不加空格
def func(arg1, arg2=10):  # 好
    pass


# 【命名规范】
# 变量和函数：小写字母，下划线分隔（snake_case）
user_name = "张三"
def calculate_total():
    pass

# 常量：全大写，下划线分隔
MAX_SIZE = 100
PI = 3.14159

# 类名：首字母大写（PascalCase）
class UserAccount:
    pass

# 私有变量/方法：以单下划线开头
_private_var = "私有"

# 特殊变量/方法：双下划线开头和结尾
# __init__, __str__, __name__


# 【导入】
# 导入应该放在文件开头
# 每个导入单独一行
# 按标准库、第三方库、本地库的顺序分组

# 好的导入方式：
# import os
# import sys
#
# import requests
#
# from my_module import my_function

# 不好的导入方式：
# import os, sys  # 不要在一行导入多个模块


# ============================================================
# 七、代码可读性技巧
# ============================================================

# 1. 使用有意义的变量名
# 不好：
d = 7
# 好：
days_in_week = 7

# 2. 避免魔法数字
score=100
# 不好：
if score > 60:
    pass
# 好：
PASS_SCORE = 60
if score > PASS_SCORE:
    pass

# 3. 保持函数简短
# 一个函数只做一件事
# 如果函数太长，考虑拆分

# 4. 使用空行分隔逻辑块
def process_data(data):
    # 第一步：验证数据
    if not data:
        return None

    # 第二步：处理数据
    result = data.strip()

    # 第三步：返回结果
    return result


# ============================================================
# 主程序入口
# ============================================================

if __name__ == "__main__":
    print("=" * 50)
    print("注释与代码风格示例")
    print("=" * 50)

    # 演示文档字符串
    print("\n调用 calculate_area 函数:")
    area = calculate_area(10, 5)
    print(f"矩形面积: {area}")

    # 演示良好的代码风格
    print("\n良好代码风格示例:")

    # 定义常量
    TAX_RATE = 0.1
    DISCOUNT_THRESHOLD = 100

    # 计算价格
    original_price = 150
    discount = 0

    # 判断是否享受折扣
    if original_price >= DISCOUNT_THRESHOLD:
        discount = original_price * 0.1  # 满100减10%

    # 计算最终价格
    final_price = original_price - discount
    tax = final_price * TAX_RATE
    total = final_price + tax

    print(f"原价: {original_price}")
    print(f"折扣: {discount}")
    print(f"税费: {tax}")
    print(f"总价: {total}")

    print("\n" + "=" * 50)
    print("本节学习完成！")
    print("=" * 50)


# ============================================================
# 本节小结
# ============================================================
#
# 1. 注释类型：
#    - 单行注释：# 注释内容
#    - 多行注释：''' 或 """
#    - 文档字符串：函数/类的第一行三引号字符串
#
# 2. 注释最佳实践：
#    - 解释"为什么"而不是"是什么"
#    - 保持注释与代码同步
#    - 删除不需要的代码，不要注释掉
#
# 3. PEP 8 代码风格：
#    - 缩进：4 个空格
#    - 行长度：不超过 79 字符
#    - 命名：snake_case（变量/函数）、PascalCase（类）
#    - 空格：运算符两边、逗号后面
#
# 4. 代码可读性：
#    - 使用有意义的变量名
#    - 避免魔法数字
#    - 保持函数简短
#    - 使用空行分隔逻辑块

