# ============================================================
# 一、print() 函数 - 输出
# ============================================================

# print() 是 Python 最常用的输出函数
# 它可以将内容显示在屏幕上

# 基本用法：输出字符串
print("Hello, World!")
print("你好，Python！")

# 输出数字
print(100)
print(3.14)

# 输出变量
name = "张三"
age = 25
print(name)
print(age)


# ============================================================
# 二、print() 的高级用法
# ============================================================

# 1. 输出多个值（用逗号分隔）
print("姓名:", name, "年龄:", age)
# 输出：姓名: 张三 年龄: 25
# 注意：逗号分隔的内容之间会自动加空格

# 2. 使用 sep 参数指定分隔符
print("苹果", "香蕉", "橙子", sep=", ")
# 输出：苹果, 香蕉, 橙子

print("2024", "01", "15", sep="-")
# 输出：2024-01-15

# 3. 使用 end 参数指定结尾字符
# 默认情况下，print() 会在末尾加换行符
print("第一行", end="")  # 不换行
print("第二行")  # 这会紧跟在第一行后面
# 输出：第一行第二行

print("A", end=" -> ")
print("B", end=" -> ")
print("C")
# 输出：A -> B -> C

# 4. 输出空行
print()  # 输出一个空行


# ============================================================
# 三、格式化输出
# ============================================================

name = "李四"
age = 30
height = 1.75
score = 95.5

# 方式一：使用 + 拼接（不推荐，需要手动转换类型）
print("\n方式一：+ 拼接")
print("姓名: " + name + ", 年龄: " + str(age))

# 方式二：使用 % 格式化（旧式写法）
print("\n方式二：% 格式化")
print("姓名: %s, 年龄: %d" % (name, age))
print("身高: %.2f 米" % height)  # %.2f 表示保留2位小数
# %s - 字符串
# %d - 整数
# %f - 浮点数
# %.2f - 保留2位小数的浮点数

# 方式三：使用 format() 方法
print("\n方式三：format() 方法")
print("姓名: {}, 年龄: {}".format(name, age))
print("姓名: {0}, 年龄: {1}, 姓名重复: {0}".format(name, age))  # 可以指定位置
print("姓名: {n}, 年龄: {a}".format(n=name, a=age))  # 可以指定名称
print("分数: {:.1f}".format(score))  # 保留1位小数

# 方式四：使用 f-string（推荐，Python 3.6+）
print("\n方式四：f-string（推荐）")
print(f"姓名: {name}, 年龄: {age}")
print(f"身高: {height:.2f} 米")  # 保留2位小数
print(f"分数: {score:.1f} 分")   # 保留1位小数

# f-string 可以直接在 {} 中进行计算
print(f"明年年龄: {age + 1}")
print(f"身高(厘米): {height * 100}")


# ============================================================
# 四、f-string 格式化详解
# ============================================================

number = 12345.6789

print("\nf-string 格式化示例:")

# 保留小数位数
print(f"保留2位小数: {number:.2f}")  # 12345.68
print(f"保留0位小数: {number:.0f}")  # 12346

# 千位分隔符
print(f"千位分隔: {number:,.2f}")  # 12,345.68

# 宽度和对齐
text = "Python"
print(f"左对齐(宽度10): '{text:<10}'")   # 'Python    '
print(f"右对齐(宽度10): '{text:>10}'")   # '    Python'
print(f"居中(宽度10): '{text:^10}'")     # '  Python  '

# 填充字符
print(f"用*填充: '{text:*^10}'")  # '**Python**'

# 百分比
ratio = 0.756
print(f"百分比: {ratio:.1%}")  # 75.6%


# ============================================================
# 五、转义字符
# ============================================================

print("\n转义字符示例:")

# \n - 换行
print("第一行\n第二行")

# \t - 制表符（Tab）
print("姓名\t年龄\t城市")
print("张三\t25\t北京")
print("李四\t30\t上海")

# \\ - 反斜杠本身
print("文件路径: C:\\Users\\Documents")

# \' 和 \" - 引号
print("他说：\"你好\"")
print('It\'s a book')

# \r - 回车（光标回到行首）
# 在某些环境下会覆盖之前的内容
print("ABCDE\rXY")  # 可能输出 XYCDE

# 原始字符串（r-string）：不处理转义字符
print("\n原始字符串:")
print(r"C:\Users\Documents")  # 不会把 \U 当作转义字符
print(r"换行符是 \n")  # 直接输出 \n，不会换行


