# 三、解释器与脚本
# ============================================================
#
# 【解释器】
# Python 是解释型语言，需要"解释器"来运行代码。
# 解释器就像一个翻译官，把 Python 代码翻译成计算机能理解的指令。
#
# 当你安装 Python 时，就安装了 Python 解释器。
# 在命令行输入 python 或 python3 就能启动解释器。
#
# 【脚本】
# 脚本就是保存 Python 代码的文件，扩展名是 .py
# 比如这个文件 python_env_intro.py 就是一个脚本。
#
# 运行脚本的方式：
#   python python_env_intro.py
#
# 【交互模式 vs 脚本模式】
#
# 交互模式：在命令行输入 python，然后逐行输入代码
#   >>> print("Hello")
#   Hello
#   >>> 2 + 3
#   5
#
# 脚本模式：把代码写在 .py 文件中，一次性运行
#   python my_script.py


