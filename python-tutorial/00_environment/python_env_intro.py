# ============================================================
# 五、if __name__ == "__main__" 详解
# ============================================================
#
# 这是 Python 中一个非常重要的惯用写法。
# 初学者经常会看到这行代码，但不理解它的作用。
#
# 【简单解释】
# 这行代码的意思是：
# "只有当这个文件被直接运行时，才执行下面的代码"
#
# 【为什么需要它？】
# Python 文件有两种使用方式：
# 1. 直接运行：python my_file.py
# 2. 被其他文件导入：import my_file
#
# 有时候我们希望某些代码只在直接运行时执行，
# 而在被导入时不执行。这时就需要这个判断。
#
# 【__name__ 是什么？】
# __name__ 是 Python 的一个特殊变量：
# - 当文件被直接运行时，__name__ 的值是 "__main__"
# - 当文件被导入时，__name__ 的值是文件名（模块名）
#
# 【示例】

def greet(name):
    """
    这是一个简单的问候函数
    参数 name: 要问候的人的名字
    """
    print(f"你好，{name}！欢迎学习 Python！")


def add(a, b):
    """
    这是一个简单的加法函数
    参数 a: 第一个数
    参数 b: 第二个数
    返回: 两数之和
    """
    return a + b


# 下面的代码只在直接运行此文件时执行
# 如果这个文件被其他文件 import，下面的代码不会执行
if __name__ == "__main__":
    # 这里通常放测试代码或主程序入口

    print("\n" + "=" * 50)
    print("欢迎来到 Python 世界！")
    print("=" * 50)

    # 测试 greet 函数
    greet("同学")

    # 测试 add 函数
    result = add(3, 5)
    print(f"3 + 5 = {result}")

    # 显示 __name__ 的值
    print(f"\n当前 __name__ 的值是: {__name__}")
    # 直接运行时会输出: __main__

    print("\n" + "=" * 50)
    print("恭喜你！成功运行了第一个 Python 程序！")
    print("=" * 50)


